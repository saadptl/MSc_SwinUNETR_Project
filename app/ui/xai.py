# ── Tab 4: Part 4.6B - Multi-Point ──────────────────────────────────────────

def _tab_part46b():
    if not _PART46B.exists():
        st.warning("Part 4.6B XAI artifacts not found.")
        return

    st.markdown('<div class="section-title" style="margin-bottom:0.8rem;">Part 4.6B — Multi-Point / Multi-Level XAI</div>', unsafe_allow_html=True)
    st.caption("Point-targeted XAI across all lumbar levels (L1/L2 – L5/S1).")

    csv_path = _PART46B / "point_results.csv"
    if csv_path.exists():
        try:
            df = pd.read_csv(csv_path)
            # Filters
            fc1, fc2, fc3 = st.columns(3)
            diseases = ["All"] + sorted(df["disease"].unique().tolist()) if "disease" in df.columns else ["All"]
            levels   = ["All"] + sorted(df["level"].unique().tolist())   if "level"   in df.columns else ["All"]

            with fc1:
                f_disease = st.selectbox("Filter: Disease", diseases, key="p46b_fd")
            with fc2:
                f_level   = st.selectbox("Filter: Level",   levels,   key="p46b_fl")
            with fc3:
                f_study   = st.text_input("Filter: Study ID", "", key="p46b_fs")

            filtered = df.copy()
            if f_disease != "All" and "disease" in filtered.columns:
                filtered = filtered[filtered["disease"] == f_disease]
            if f_level != "All" and "level" in filtered.columns:
                filtered = filtered[filtered["level"] == f_level]
            if f_study.strip() and "study_id" in filtered.columns:
                filtered = filtered[filtered["study_id"].astype(str).str.contains(f_study.strip())]

            display_cols = [c for c in [
                "point_index","disease","level","target_probability",
                "centroid_distance","r10_concentration"
            ] if c in filtered.columns]

            st.dataframe(filtered[display_cols].reset_index(drop=True) if display_cols else filtered,
                         use_container_width=True)
            st.caption(f"Showing {len(filtered)} of {len(df)} points")

        except Exception as exc:
            st.error("Failed to load point_results.csv.")
            with st.expander("Technical details"):
                st.exception(exc)
    else:
        st.warning("point_results.csv not found.")

    # Show available visualization images
    for disease_dir in sorted(_PART46B.iterdir()):
        if disease_dir.is_dir():
            pngs = sorted(disease_dir.glob("*.png"))
            if pngs:
                with st.expander(f"🖼️ {disease_dir.name.replace('_',' ')} — {len(pngs)} visualizations"):
                    cols = st.columns(min(3, len(pngs)))
                    for i, p in enumerate(pngs[:6]):
                        with cols[i % min(3, len(pngs))]:
                            st.image(str(p), caption=p.stem, use_container_width=True)


