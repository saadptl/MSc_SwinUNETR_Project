def _tab_part46c():
    if not _PART46C.exists():
        st.warning("Part 4.6C XAI artifacts not found.")
        return

    st.markdown('<div class="section-title" style="margin-bottom:0.8rem;">Part 4.6C — Quantitative XAI Analysis</div>', unsafe_allow_html=True)
    st.caption("Attribution distance · R10 concentration · Disease comparison · Level-wise analysis")

    # Overall summary metrics
    overall_csv = _PART46C / "part46c_overall_summary.csv"
    if overall_csv.exists():
        try:
            df = pd.read_csv(overall_csv)
            metric_map = {
                "centroid_distance":      ("Centroid Distance",     "voxels"),
                "max_attribution_distance":("Max Attribution Dist.", "voxels"),
                "r10_concentration":      ("R10 Concentration",     "mean"),
            }
            cols = st.columns(len(metric_map))
            for col, (metric, (label, unit)) in zip(cols, metric_map.items()):
                row = df[df["metric"] == metric]
                if not row.empty:
                    mean_val = float(row["mean"].iloc[0])
                    with col:
                        st.metric(label, f"{mean_val:.3f}", help=unit)
        except Exception:
            pass

    # PNG visualizations
    png_map = {
        "part46c_comparison.png":                       "Overall Comparison",
        "part46c_centroid_distance_comparison.png":     "Centroid Distance",
        "part46c_r10_concentration_comparison.png":     "R10 Concentration",
        "part46c_max_attribution_distance_comparison.png": "Max Attribution Distance",
        "part46c_disease_level_heatmap.png":            "Disease-Level Heatmap",
        "part46c_levelwise.png":                        "Level-wise Analysis",
    }

    vis_c1, vis_c2 = st.columns(2)
    cols_cycle = [vis_c1, vis_c2]
    i = 0
    for fname, title in png_map.items():
        p = _PART46C / fname
        if p.exists():
            with cols_cycle[i % 2]:
                st.markdown(f"**{title}**")
                st.image(str(p), use_container_width=True)
            i += 1

    # Disease-wise CSV
    disease_csv = _PART46C / "part46c_disease_summary.csv"
    if disease_csv.exists():
        with st.expander("📊 Disease-wise Quantitative Summary"):
            try:
                st.dataframe(pd.read_csv(disease_csv), use_container_width=True)
            except Exception:
                st.warning("Could not load disease summary CSV.")

    # Level-wise CSV
    level_csv = _PART46C / "part46c_level_summary.csv"
    if level_csv.exists():
        with st.expander("📊 Level-wise Quantitative Summary"):
            try:
                st.dataframe(pd.read_csv(level_csv), use_container_width=True)
            except Exception:
                st.warning("Could not load level summary CSV.")


