# ── Tab 1: Classification XAI ────────────────────────────────────────────────

def _tab_classification_xai():
    s = _session()

    if s is None:
        st.info("Run an MRI analysis first. Classification XAI (Grad-CAM) requires an active inference session.")
        if st.button("🩻 Go to MRI Analysis", type="primary", key="xai_cls_goto"):
            navigate("🩻 MRI Analysis")
        return

    c1, c2, c3 = st.columns(3)
    with c1:
        st.metric("Prediction",   safe(s.predicted_class))
    with c2:
        st.metric("Confidence",   f"{pct(s.confidence):.2f}%")
    with c3:
        st.metric("Target Class", safe(s.predicted_class))

    st.markdown("---")

    if s.has_xai:
        st.success("✅ Grad-CAM explanation is available for this analysis.")
    else:
        st.info("Generate Grad-CAM. This uses the existing checkpoint — no retraining.")

    if st.button("🔬 Generate XAI Explanation", type="primary", use_container_width=False, key="generate_xai_cls"):
        with st.spinner("Generating Grad-CAM from the existing trained model..."):
            try:
                if len(s.selected_files) != 3:
                    raise RuntimeError("XAI requires exactly 3 adjacent DICOM slices from the current analysis.")
                from xai_dashboard import explain_dicom_series
                result = explain_dicom_series(
                    [str(p) for p in s.selected_files],
                    target_class=s.predicted_class_id,
                    output_name="dashboard_current_analysis",
                )
                outputs = result.get("outputs", {}) if isinstance(result, dict) else {}
                s.xai_result  = result
                s.xai_paths   = {k: str(v) for k, v in outputs.items() if v}
                s.gradcam_generated = bool(s.xai_paths)
                st.success("Grad-CAM generated successfully.")
                st.rerun()
            except Exception as exc:
                st.error("XAI generation failed. The model checkpoint was not modified.")
                with st.expander("Technical details"):
                    st.exception(exc)

    if not s.has_xai or not s.xai_paths:
        return

    st.markdown("---")
    st.markdown('<div class="section-title" style="margin-bottom:0.8rem;">🖼️ Grad-CAM Visualization</div>', unsafe_allow_html=True)

    paths = s.xai_paths
    images = [
        (paths.get("middle_slice"), "MRI Middle Slice"),
        (paths.get("heatmap"),      "Grad-CAM Heatmap"),
        (paths.get("overlay"),      "Model Attention Overlay"),
    ]
    cols = st.columns(3)
    for col, (path, title) in zip(cols, images):
        with col:
            st.markdown(f"**{title}**")
            if path and Path(path).exists():
                st.image(path, use_container_width=True)
            else:
                st.warning("Image not found.")

    panel = paths.get("panel")
    if panel and Path(panel).exists():
        st.markdown("**XAI Summary Panel**")
        st.image(panel, use_container_width=True)

    xai = s.xai_result.get("xai", {}) if isinstance(s.xai_result, dict) else {}
    if xai:
        c1, c2, c3 = st.columns(3)
        with c1: st.metric("Feature Shape", str(xai.get("feature_shape", "N/A")))
        with c2: st.metric("CAM Mean",       f"{float(xai.get('cam_mean', 0)):.4f}")
        with c3: st.metric("CAM Std",        f"{float(xai.get('cam_std', 0)):.4f}")

    st.caption("Brighter Grad-CAM regions indicate stronger model-attention for the target class. Not a disease segmentation map.")


